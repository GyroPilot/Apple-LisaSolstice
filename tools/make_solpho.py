"""make_solpho.py  3-Nov-2026: pictures from Tim and Connie's Winter Solstice talk -> SOL-PHO.TEXT, unit SolPho
for LisaSolstice REV B.  Tim, 3 Nov: "A ok, b ok, h ok" (the Yule log engraving, the Serpent Mound postcard, the
1600s engraving of the heavens).  Same row code as SOL-PIC (make_solpic.py): 6 bits a character, chr(48 + v),
most significant bit first, 1 = black, trailing '0's dropped; 16 rows a procedure (Error 350 otherwise); a new
segment whenever one would pass about 12K characters of picture (32K segment limit).
    py -3.12 make_solpho.py <sources_raw dir>"""
import sys
from PIL import Image

R = "C:/Users/BananaAdmin/code/sol-work/research/"
PICS = [("L", R + "lisa_L_newgrange_plan_1903.png"),       # REV C order: oldest site first
        ("K", R + "lisa_K_newgrange_sunlight.png"),
        ("P", R + "lisa_P_stonehenge_sunset.png"),
        ("B", R + "lisa_B_serpent_mound_postcard.png"),
        ("A", R + "lisa_A_yule_log_engraving.png"),
        ("H", R + "lisa_H_cosmology_engraving.png")]
GROUP, SEGMAX = 16, 20000   # REV C: 20K (fewer segments; still well under 32K)

out_dir = sys.argv[1]
pics = []
for key, path in PICS:
    im = Image.open(path).convert("1")
    w, h = im.size
    ch = (w + 5) // 6
    ch = (ch + 3) // 4 * 4                   # whole groups of four characters
    nbytes = ch // 4 * 3
    rb = nbytes + (nbytes % 2)               # rowBytes must be even
    rows = []
    for y in range(h):
        bits = [1 if im.getpixel((x, y)) == 0 else 0 for x in range(w)] + [0] * (ch * 6 - w)
        s = "".join(chr(48 + int("".join(map(str, bits[i:i + 6])), 2)) for i in range(0, ch * 6, 6))
        s = s.rstrip("0")
        assert "'" not in s and "{" not in s and "}" not in s
        rows.append(s)
    pics.append(dict(key=key, w=w, h=h, ch=ch, rb=rb, rows=rows))

maxrb = max(p["rb"] for p in pics)
bandb = maxrb * GROUP
body, seg, segn, segs = [], 0, 0, []


def newseg(name):
    body.append("{$S %s}\n\n" % name)
    segs.append(name)


total = 0
for p in pics:
    k = p["key"]
    nproc = (p["h"] + GROUP - 1) // GROUP
    part = 1
    newseg("SOLPh%s%d" % (k, part))
    seg = 0
    for n in range(nproc):
        lo, hi = n * GROUP, min(p["h"], (n + 1) * GROUP)
        size = sum(len(p["rows"][y]) for y in range(lo, hi))
        if seg + size > SEGMAX:
            part += 1
            newseg("SOLPh%s%d" % (k, part))
            seg = 0
        seg += size
        total += size
        lines = ["procedure Ph%sR%02d (y : integer; var s : Str255);" % (k, n), "begin", "   case y of"]
        lines += ["%d: s := '%s';" % (y, p["rows"][y]) for y in range(lo, hi)]
        lines += ["      otherwise", "         s := ''", "   end", "end;", ""]
        body.append("\n".join(lines) + "\n")
    # the row dispatcher for this picture, in the drawing segment
    p["nproc"] = nproc

disp = []
for p in pics:
    k = p["key"]
    d = ["procedure Ph%sRow (y : integer; var s : Str255);" % k, "begin", "   case y div %d of" % GROUP]
    d += ["      %d: Ph%sR%02d(y, s);" % (n, k, n) for n in range(p["nproc"])]
    d += ["      otherwise", "         s := ''", "   end", "end;", ""]
    disp.append("\n".join(d) + "\n")

case_w = "\n".join("      %d: PhW := %d;" % (i + 1, p["w"]) for i, p in enumerate(pics))
case_h = "\n".join("      %d: PhH := %d;" % (i + 1, p["h"]) for i, p in enumerate(pics))
case_rb = "\n".join("      %d: rb := %d;" % (i + 1, p["rb"]) for i, p in enumerate(pics))
case_row = "\n".join("            %d: Ph%sRow(y, s);" % (i + 1, p["key"]) for i, p in enumerate(pics))

src = """unit SolPho;

{ SOL-PHO.TEXT -- LisaSolstice (tool 419326): pictures from Tim and Connie  }
{ O'Connor's Winter Solstice talk, page P (Seasons > Pictures from History).}
{ REV C  3-Nov-2026  Six pictures, oldest site first (Tim, 3 Nov):       }
{                    1 Newgrange plan and section, Wakeman 1903 (PD);    }
{                    2 midwinter sunlight in the Newgrange chamber,      }
{                      photo Dentp, CC BY-SA 4.0 (Wikimedia Commons);    }
{                    3 Stonehenge at sunset, photo Jeffrey Pfau,         }
{                      CC BY-SA 3.0 (Wikimedia Commons);                 }
{                    4 the Great Serpent Mound, Ohio, an early postcard; }
{                    5 the Yule log, a 19th-century wood engraving;      }
{                    6 the heavens, an engraving of the 1600s.           }
{                    The two photos as converted here are CC BY-SA too.  }
{ REV B  3-Nov-2026  Three pictures (4, 5, 6 above).                     }
{                    Generated by make_solpho.py: do not edit the rows by  }
{                    hand.  %d characters of picture.                   }
{ Each row: 6 bits a character, chr(48 + v), most significant bit first,   }
{ 1 = black, trailing '0's left off.  Drawn in 16-row bands with CopyBits, }
{ as SOL-PIC.  Data in code: segments %s.            }

INTERFACE

uses (*$U UnitStd.obj *)   UnitStd,
     (*$U UnitHz.obj *)    UnitHz,
     (*$U Storage.obj *)   Storage,
     (*$U QuickDraw.obj *) QuickDraw;

const
   phN = %d;                 { pictures }

function  PhW (n : integer) : integer;
function  PhH (n : integer) : integer;
procedure PhDraw (n, left, top : integer);

IMPLEMENTATION

""" % (total, " ".join(segs), len(pics))
src += "".join(body)
src += """{$S SOLPhoD}

const
   phBandH = 16;

type PhBand = record
                 case integer of
                    0 : (b : packed array [0..%d] of -128..127);
                    1 : (w : array [0..%d] of integer)
              end;

var ph : PhBand;

""" % (bandb - 1, bandb // 2 - 1)
src += "".join(disp)
src += """function PhW {n : integer} : integer;
begin
   case n of
%s
      otherwise
         PhW := 0
   end
end;

function PhH {n : integer} : integer;
begin
   case n of
%s
      otherwise
         PhH := 0
   end
end;

procedure PhPut (i, v : integer);
{ Byte i of the band gets v (0..255). }
begin
   if v > 127 then v := v - 256;
   ph.b[i] := v
end;

procedure PhDraw {n, left, top : integer};
{ Picture n with its top left corner at (left, top) in the current port, }
{ 16 rows at a time; bands outside the visible region are skipped.        }
var band, y0, y1, y, i, k, base, len, w, h, rb : integer;
    v0, v1, v2, v3                           : integer;
    s                                        : Str255;
    bm                                       : BitMap;
    sr, dr, vb                               : Rect;
begin
   w := PhW(n);
   h := PhH(n);
   if (w = 0) or (h = 0) then
      exit(PhDraw);
   case n of
%s
      otherwise
         rb := 2
   end;
   vb := thePort^.visRgn^^.rgnBBox;
   bm.baseAddr := @ph;
   bm.rowBytes := rb;
   for band := 0 to (h - 1) div phBandH do begin
      y0 := band * phBandH;
      y1 := y0 + phBandH - 1;
      if y1 > h - 1 then
         y1 := h - 1;
      if (top + y1 >= vb.top) and (top + y0 < vb.bottom) then begin
         for i := 0 to (rb * phBandH) div 2 - 1 do
            ph.w[i] := 0;
         for y := y0 to y1 do begin
            case n of
%s
               otherwise
                  s := ''
            end;
            len := length(s);
            base := (y - y0) * rb;
            k := 0;
            while k < len do begin
               { four characters -> three bytes; missing characters are 0 }
               v0 := ord(s[k + 1]) - 48;
               if k + 2 <= len then v1 := ord(s[k + 2]) - 48 else v1 := 0;
               if k + 3 <= len then v2 := ord(s[k + 3]) - 48 else v2 := 0;
               if k + 4 <= len then v3 := ord(s[k + 4]) - 48 else v3 := 0;
               i := base + (k div 4) * 3;
               PhPut(i, v0 * 4 + v1 div 16);
               PhPut(i + 1, (v1 mod 16) * 16 + v2 div 4);
               PhPut(i + 2, (v2 mod 4) * 64 + v3);
               k := k + 4
            end
         end;
         SetRect(bm.bounds, 0, 0, w, y1 - y0 + 1);
         SetRect(sr, 0, 0, w, y1 - y0 + 1);
         SetRect(dr, left, top + y0, left + w, top + y1 + 1);
         CopyBits(bm, thePort^.portBits, sr, dr, srcCopy, nil)
      end
   end
end;

end.
""" % (case_w, case_h, case_rb, case_row)
open(out_dir + "/SOL-PHO.TEXT", "w", newline="\n").write(src)
for p in pics:
    print(p["key"], p["w"], "x", p["h"], "rowBytes", p["rb"], "chars", sum(len(r) for r in p["rows"]),
          "procedures", p["nproc"])
print("segments", segs, "total chars", total, "band bytes", bandb, "file", len(src))

# REV B (2): the build disk's free space is in runs too short for one 78K file (LisaFileSystemTool put: "the
# smallmap is full", 9 runs).  Each picture's rows go into an include file, as Apple's LIBTK does ({$I ...}).
full = open(out_dir + "/SOL-PHO.TEXT", newline="\n").read()
main = full
for p in pics:
    k = p["key"]
    a = full.index("{$S SOLPh%s1}" % k)
    nxt = [full.index("{$S SOLPh%s1}" % q["key"]) for q in pics if full.index("{$S SOLPh%s1}" % q["key"]) > a]
    b = min(nxt) if nxt else full.index("{$S SOLPhoD}")
    chunk = full[a:b]
    open(out_dir + "/SOL-PHO%s.TEXT" % k, "w", newline="\n").write(
        "{ SOL-PHO%s.TEXT -- included by SOL-PHO.TEXT (unit SolPho): picture %s's rows.  Generated by make_solpho.py. }\n\n"
        % (k, k) + chunk)
    main = main.replace(chunk, "{$I SOL/PHO%s.TEXT}\n\n" % k)
open(out_dir + "/SOL-PHO.TEXT", "w", newline="\n").write(main)
import os
print("split:", ", ".join("%s %d" % (f, os.path.getsize(out_dir + "/" + f)) for f in
                          ["SOL-PHO.TEXT"] + ["SOL-PHO%s.TEXT" % p["key"] for p in pics]))
