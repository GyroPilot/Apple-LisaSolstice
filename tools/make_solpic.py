"""make_solpic.py  2-Nov-2026: Tim's solargraph (method 4: blue channel, Floyd-Steinberg) -> SOL-PIC.TEXT,
unit SolPic for LisaSolstice.  640 x 271 Lisa pixels.  Each row is 108 characters of 6 bits (chr(48 + v), '0'..'o',
none of ' { } ( ) *), most significant bit first, 1 = black; trailing '0's dropped.  Four characters are three
bytes, so a row decodes to 81 bytes.
REV B 2-Nov: 16 rows a procedure.  REV A put 136 rows (15K of literals) in one procedure: Lisa Pascal stopped with
Error 350 "Procedure too large".  Procedures 0-8 in segment SOLPicA, 9-16 in SOLPicB (each segment under 32K)."""
from PIL import Image
W, H, CH, GROUP = 640, 271, 108, 16
NPROC = (H + GROUP - 1) // GROUP          # 17
HALF = NPROC // 2 + 1                     # procedures 0..8 in SOLPicA
im = Image.open('4_blue_floyd.png').convert('1')
assert im.size == (W, H), im.size
rows = []
for y in range(H):
    bits = [1 if im.getpixel((x, y)) == 0 else 0 for x in range(W)] + [0] * (CH * 6 - W)
    s = ''.join(chr(48 + int(''.join(map(str, bits[i:i + 6])), 2)) for i in range(0, CH * 6, 6))
    rows.append(s.rstrip('0'))
for s in rows:
    assert "'" not in s and '{' not in s and '}' not in s
total = sum(len(s) for s in rows)

def proc(k):
    lo, hi = k * GROUP, min(H, (k + 1) * GROUP)
    out = ["procedure SpR%02d (y : integer; var s : Str255);" % k, "begin", "   case y of"]
    for y in range(lo, hi):
        out.append("%d: s := '%s';" % (y, rows[y]))
    out += ["      otherwise", "         s := ''", "   end", "end;", ""]
    return "\n".join(out) + "\n"

src = """unit SolPic;

{ SOL-PIC.TEXT -- LisaSolstice (tool 419326): the splash picture.          }
{ REV B  2-Nov-2026  16 rows a procedure (REV A's 136 in one procedure:     }
{                    Error 350 Procedure too large).                        }
{ REV A  2-Nov-2026  Tim O'Connor's solargraph: a pinhole camera in a pop   }
{                    can on the roof of his house in Cincinnati, exposed   }
{                    from the June solstice to the December solstice; each }
{                    arc is one day's path of the Sun.  Blue channel,      }
{                    Floyd-Steinberg dither (Tim's pick, method 4), 640 x  }
{                    271 Lisa pixels.  Generated by make_solpic.py: do not }
{                    edit the rows by hand.  %d characters of picture.   }
{ Each row: 108 characters of 6 bits, chr(48 + v), most significant bit   }
{ first, 1 = black, trailing '0's left off.  Drawn in 16-row bands with    }
{ CopyBits (LisaFuji's world map method).  Data in code, two segments.    }

INTERFACE

uses (*$U UnitStd.obj *)   UnitStd,
     (*$U UnitHz.obj *)    UnitHz,
     (*$U Storage.obj *)   Storage,
     (*$U QuickDraw.obj *) QuickDraw;

const
   spW = 640;                { picture width, Lisa pixels }
   spH = 271;                { picture height }

procedure SpDraw (left, top : integer);

IMPLEMENTATION

{$S SOLPicA}

const
   spRb    = 82;             { bytes in a band row: even, at least 81 }
   spBandH = 16;

type SpBand = record
                 case integer of
                    0 : (b : packed array [0..1311] of -128..127);
                    1 : (w : array [0..655] of integer)
              end;

var sp : SpBand;

""" % total
for k in range(NPROC):
    if k == HALF:
        src += "{$S SOLPicB}\n\n"
    src += proc(k)
src += "{$S SOLPicA}\n\nprocedure SpRow (y : integer; var s : Str255);\n{ Row y, from the procedure that holds it. }\nbegin\n   case y div %d of\n" % GROUP
for k in range(NPROC):
    src += "      %d: SpR%02d(y, s);\n" % (k, k)
src += """      otherwise
         s := ''
   end
end;

procedure SpPut (i, v : integer);
{ Byte i of the band gets v (0..255). }
begin
   if v > 127 then v := v - 256;
   sp.b[i] := v
end;

procedure SpDraw {left, top : integer};
{ The picture with its top left corner at (left, top) in the current port, }
{ 16 rows at a time; bands outside the visible region are skipped.          }
var band, y0, y1, y, i, k, base, n : integer;
    v0, v1, v2, v3                 : integer;
    s                              : Str255;
    bm                             : BitMap;
    sr, dr, vb                     : Rect;
begin
   vb := thePort^.visRgn^^.rgnBBox;
   bm.baseAddr := @sp;
   bm.rowBytes := spRb;
   for band := 0 to (spH - 1) div spBandH do begin
      y0 := band * spBandH;
      y1 := y0 + spBandH - 1;
      if y1 > spH - 1 then
         y1 := spH - 1;
      if (top + y1 >= vb.top) and (top + y0 < vb.bottom) then begin
         for i := 0 to (spRb * spBandH) div 2 - 1 do
            sp.w[i] := 0;
         for y := y0 to y1 do begin
            SpRow(y, s);
            n := length(s);
            base := (y - y0) * spRb;
            k := 0;
            while k < n do begin
               { four characters -> three bytes; missing characters are 0 }
               v0 := ord(s[k + 1]) - 48;
               if k + 2 <= n then v1 := ord(s[k + 2]) - 48 else v1 := 0;
               if k + 3 <= n then v2 := ord(s[k + 3]) - 48 else v2 := 0;
               if k + 4 <= n then v3 := ord(s[k + 4]) - 48 else v3 := 0;
               i := base + (k div 4) * 3;
               SpPut(i, v0 * 4 + v1 div 16);
               SpPut(i + 1, (v1 mod 16) * 16 + v2 div 4);
               SpPut(i + 2, (v2 mod 4) * 64 + v3);
               k := k + 4
            end
         end;
         SetRect(bm.bounds, 0, 0, spW, y1 - y0 + 1);
         SetRect(sr, 0, 0, spW, y1 - y0 + 1);
         SetRect(dr, left, top + y0, left + spW, top + y1 + 1);
         CopyBits(bm, thePort^.portBits, sr, dr, srcCopy, nil)
      end
   end
end;

end.
"""
open('../sol_rev_a/sources_raw/SOL-PIC.TEXT', 'w', newline='\n').write(src)
a = sum(len(rows[y]) for y in range(min(H, HALF * GROUP)))
print('rows', H, 'chars', total, 'segment A', a, 'segment B', total - a, 'procedures', NPROC,
      'largest procedure', max(sum(len(rows[y]) for y in range(k * GROUP, min(H, (k + 1) * GROUP))) for k in range(NPROC)))
